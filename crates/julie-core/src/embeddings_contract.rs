//! Shared embedding contract types — the trait and its companion structs.
//!
//! Lives here in `julie-core` (the bottom leaf crate) so that both the main
//! `julie` crate and any future sibling crates can depend on a single
//! definition. The `julie::embeddings` module re-exports everything from here,
//! so all existing `crate::embeddings::*` import paths remain valid.

use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

pub use crate::embeddings_identity::EncoderIdentity;

/// Semantic retrieval execution mode across CLI and MCP transports.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum SemanticMode {
    #[default]
    Auto,
    Off,
    Required,
}

impl SemanticMode {
    pub fn is_off(&self) -> bool {
        matches!(self, Self::Off)
    }

    pub fn is_required(&self) -> bool {
        matches!(self, Self::Required)
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Off => "off",
            Self::Required => "required",
        }
    }
}

/// Query embedding tagged with the generating encoder key and source revision.
///
/// Ensures readers only compare vectors generated by the same encoder model
/// against the same workspace revision, preventing torn reads and mixed-model KNN comparisons.
#[derive(Clone, Debug, PartialEq)]
pub struct TaggedQueryEmbedding {
    pub vector: Vec<f32>,
    pub encoder_key: String,
    pub source_revision: i64,
}

impl TaggedQueryEmbedding {
    pub fn new(vector: Vec<f32>, encoder_key: impl Into<String>, source_revision: i64) -> Self {
        Self {
            vector,
            encoder_key: encoder_key.into(),
            source_revision,
        }
    }

    pub fn untagged(vector: Vec<f32>) -> Self {
        Self {
            vector,
            encoder_key: String::new(),
            source_revision: 0,
        }
    }

    pub fn is_tagged(&self) -> bool {
        !self.encoder_key.is_empty()
    }
}

impl From<Vec<f32>> for TaggedQueryEmbedding {
    fn from(vector: Vec<f32>) -> Self {
        Self::untagged(vector)
    }
}

